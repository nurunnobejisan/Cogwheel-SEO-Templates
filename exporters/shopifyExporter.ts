/**
 * Cogwheel SEO Templates — Shopify Liquid Exporter
 * 
 * Generates Shopify Liquid snippets (.liquid) and sections,
 * properly mapping SEO metadata and content to Shopify Liquid object models
 * (product.*, collection.*, page.*) without corrupting native Liquid syntax.
 */

export interface ShopifyExportPayload {
  scope: "product" | "collection" | "page";
  title?: string;
  metaDescription?: string;
  snippetName: string;
  richContentHtml: string;
  schemaJsonLd?: string;
}

export function exportToShopifyLiquid(payload: ShopifyExportPayload): string {
  const scopePrefix = payload.scope;

  const headerComment = `{%- comment -%}
  Auto-generated by Cogwheel SEO Studio — Shopify Liquid Adapter
  Snippet: ${payload.snippetName}.liquid
  Scope: ${payload.scope}
{%- endcomment -%}`;

  const seoMetaLiquid = `
{%- if ${scopePrefix}.metafields.seo.title != blank -%}
  <title>{{ ${scopePrefix}.metafields.seo.title | escape }}</title>
{%- else -%}
  <title>{{ ${scopePrefix}.title | escape }} | {{ shop.name }}</title>
{%- endif -%}

{%- if ${scopePrefix}.metafields.seo.description != blank -%}
  <meta name="description" content="{{ ${scopePrefix}.metafields.seo.description | escape }}">
{%- elsif ${scopePrefix}.description != blank -%}
  <meta name="description" content="{{ ${scopePrefix}.description | strip_html | truncatewords: 25 | escape }}">
{%- endif -%}
<link rel="canonical" href="{{ canonical_url }}">
`;

  const structuredDataLiquid = payload.schemaJsonLd
    ? `\n<script type="application/ld+json">\n${payload.schemaJsonLd}\n</script>\n`
    : "";

  const sectionHtml = `
<div class="cogwheel-seo-section cogwheel-${scopePrefix}-container" data-scope="${scopePrefix}">
  <article class="prose max-w-none">
    ${payload.richContentHtml}
  </article>
</div>
`;

  return `${headerComment}\n${seoMetaLiquid}${structuredDataLiquid}${sectionHtml}`.trim();
}
