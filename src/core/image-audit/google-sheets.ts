import { getDriveClient, getSheetsClient, isGoogleConfigured } from "../google.ts";
import type { CrawlLogEntry, ImageAuditItem, ImageAuditSummary } from "./types.ts";

export async function exportAuditToGoogleSheets(
  summary: ImageAuditSummary,
  items: ImageAuditItem[],
  crawlLog: CrawlLogEntry[]
): Promise<{ spreadsheetId: string; spreadsheetUrl: string }> {
  if (!isGoogleConfigured()) {
    throw new Error(
      "Google Workspace service account is not configured. Set GOOGLE_SERVICE_ACCOUNT_B64 or GOOGLE_SERVICE_ACCOUNT_JSON in environment variables."
    );
  }

  const drive = getDriveClient();
  const sheets = getSheetsClient();

  const title = `Image Optimization Audit — ${new URL(summary.websiteUrl).hostname} (${new Date().toISOString().split("T")[0]})`;
  const folderId = process.env.GOOGLE_DRIVE_ROOT_FOLDER_ID || undefined;

  // 1. Create native Google Sheet
  const createRes = await drive.files.create({
    supportsAllDrives: true,
    requestBody: {
      name: title,
      mimeType: "application/vnd.google-apps.spreadsheet",
      ...(folderId ? { parents: [folderId] } : {}),
    },
    fields: "id, webViewLink",
  });

  const spreadsheetId = createRes.data.id!;
  const spreadsheetUrl =
    createRes.data.webViewLink || `https://docs.google.com/spreadsheets/d/${spreadsheetId}/edit`;

  // 2. Setup tabs: "Image Optimization", "Overview", "Image Inventory", "Recommendations", "Crawl Log"
  const batchUpdateRequest = {
    requests: [
      {
        updateSheetProperties: {
          properties: {
            sheetId: 0,
            title: "Image Optimization",
          },
          fields: "title",
        },
      },
      { addSheet: { properties: { sheetId: 1, title: "Overview" } } },
      { addSheet: { properties: { sheetId: 2, title: "Image Inventory" } } },
      { addSheet: { properties: { sheetId: 3, title: "Recommendations" } } },
      { addSheet: { properties: { sheetId: 4, title: "Crawl Log" } } },
    ],
  };

  await sheets.spreadsheets.batchUpdate({
    spreadsheetId,
    requestBody: batchUpdateRequest,
  });

  // 3. Populate Image Optimization tab (EXACT 6-COLUMN LAYOUT MATCHING REFERENCE SHEET)
  const optHeaders = [
    "Image",
    "URL ",
    "Title ",
    "Length",
    "Optimized ALT Text",
    "Length",
  ];
  const optValues = [
    optHeaders,
    ...items.map((item, idx) => {
      const r = idx + 2;
      return [
        `=IMAGE(B${r})`,
        item.imageUrl,
        item.filename,
        `=LEN(C${r})`,
        item.proposedAlt,
        `=LEN(E${r})`,
      ];
    }),
  ];

  // 4. Populate Audit Summary tab
  const summaryValues = [
    ["WEBSITE IMAGE OPTIMIZATION AUDIT SUMMARY", ""],
    ["Generated By:", "Cogwheel SEO & Hospitality Templates Studio (Razib Marketing)"],
    ["Audited Website URL:", summary.websiteUrl],
    ["Origin Domain:", summary.origin],
    ["Audit Timestamp (UTC):", summary.crawledAt],
    ["Total Duration:", `${Math.round(summary.durationMs / 1000)} seconds`],
    ["Crawl Limit:", `${summary.maxPagesLimit} pages`],
    ["Crawl Status:", summary.crawlCompleted ? "Complete within crawl limits" : `Stopped: ${summary.stoppedReason}`],
    ["", ""],
    ["DISCOVERY & COVERAGE METHODS", "STATUS / METRIC"],
    ["Discovery Methods Deployed:", (summary.discoveryMethods || []).join(", ")],
    ["XML Sitemap Discovery:", summary.sitemapDiscoverySucceeded ? `Succeeded (${summary.sitemapUrlsFound} URLs found)` : "None detected / Inaccessible"],
    ["WordPress REST Media API:", summary.wpMediaApiFound ? `Discovered (${summary.wpMediaCount} media items)` : "Not applicable / Inaccessible"],
    ["JavaScript Client-Rendering:", summary.jsRenderingInspected ? "Inspected" : "Static HTML & SSR DOM only"],
    ["Coverage Statement:", summary.coverageStatement],
    ["", ""],
    ["KEY AUDIT TOTALS", "COUNT"],
    ["Pages Discovered:", summary.pagesDiscovered || summary.pagesScanned],
    ["Pages Successfully Scanned:", summary.pagesScanned],
    ["Pages Failed / Timed Out:", summary.pagesFailed],
    ["Total Image Placements (Occurrences):", summary.totalPlacementsCount || summary.totalImagesFound],
    ["Unique Image URLs (Distinct Assets):", summary.uniqueImagesCount],
    ["Images Successfully Reachable (HTTP 200):", summary.imagesPreviewedSuccessfully],
    ["Broken Image Links (HTTP 4xx / 5xx):", summary.brokenImagesCount],
    ["Images Missing ALT Text:", summary.missingAltCount],
    ["Decorative Empty Alt Placements (alt=\"\"):", summary.decorativeEmptyAltCount],
    ["Oversized Assets (>100KB Threshold):", summary.oversizedImagesCount],
    ["Missing HTML Dimensions (CLS Risk):", summary.missingDimensionsCount],
    ["Legacy Formats (JPEG / PNG eligible for WebP/AVIF):", summary.legacyFormatCount],
    ["Lazy-Loaded Above-The-Fold / Hero Images:", summary.aboveFoldLazyCount],
    ["", ""],
    ["FORMAT BREAKDOWN", "ASSET COUNT"],
    ...Object.entries(summary.formatBreakdown || {}).map(([fmt, count]) => [fmt, count]),
    ["", ""],
    ["IMPORTANT COVERAGE LIMITATIONS & NOTICE", ""],
    ["Completeness Boundary:", "This audit reflects images discovered on crawlable public HTML pages and referenced sitemaps. Pages gated by authentication, robots.txt exclusions, JavaScript-only SPAs, or firewall rate-limits could not be reached."],
    ["WCAG Decorative Images:", "Empty alt text (alt=\"\") is valid and recommended by WCAG 2.1 AA for purely decorative backgrounds, borders, and layout icons. Not all empty alt attributes represent defects."],
    ["Automated Alt Text:", "Proposed alt text strings are generated from contextual page titles, headings, and clean filename tokens. Review descriptions before deploying to production."],
    ["", ""],
    ["KEY FINDINGS & RECOMMENDATIONS", ""],
    ...(summary.topFindings || []).map((finding, idx) => [`${idx + 1}.`, finding]),
  ];

  // 5. Populate Image Inventory tab
  const invHeaders = [
    "Image URL",
    "Page URL",
    "Page Title",
    "Page Status",
    "Original Filename",
    "Target Filename (WebP)",
    "Current ALT",
    "Proposed ALT",
    "Is Decorative",
    "Format",
    "MIME Type",
    "File Size (KB)",
    "HTML Width",
    "HTML Height",
    "Natural Width",
    "Natural Height",
    "Loading Attribute",
    "Element Type",
    "Occurrences",
    "HTTP Status",
    "Flagged Issues",
    "Recommendation",
    "Priority",
  ];
  const invValues = [
    invHeaders,
    ...items.map((item) => [
      item.imageUrl,
      item.pageUrl,
      item.pageTitle || "-",
      item.pageStatus,
      item.filename || "-",
      item.targetFilename || "-",
      item.currentAlt === null ? "[MISSING]" : item.currentAlt === "" ? '"" (Empty)' : item.currentAlt,
      item.proposedAlt,
      item.isDecorative ? "Yes (Decorative)" : "No",
      item.format,
      item.mimeType,
      item.fileSizeKb ?? "-",
      item.htmlWidth ?? "-",
      item.htmlHeight ?? "-",
      item.naturalWidth ?? "-",
      item.naturalHeight ?? "-",
      item.loadingAttribute,
      item.elementType,
      item.occurrenceCount,
      item.httpStatus,
      item.issues.map((i) => i.label).join("; ") || "None",
      item.recommendation,
      item.priority,
    ]),
  ];

  // 6. Populate Recommendations tab
  const recValues = [
    ["Issue Category", "Why It Matters", "Recommended Fix", "Industry Standard / Priority"],
    [
      "Missing Alt Attributes",
      "Screen readers cannot announce image content, and search engines cannot index image context for Google Images and web search.",
      "Add concise, descriptive alt text to all informational images. Purely decorative elements (dividers, borders, shadows) should use alt=\"\" or CSS background.",
      "WCAG 2.1 AA / High Priority",
    ],
    [
      "Oversized File Sizes (>100KB)",
      "Heavy assets consume cellular bandwidth, stall page rendering, and increase bounce rates, especially on mobile devices.",
      "Compress images using modern tools (Squoosh, Sharp, TinyPNG) and target under 100KB for standard content images (under 200KB for full-width hero banners).",
      "Core Web Vitals (LCP) / High Priority",
    ],
    [
      "Legacy Image Formats (JPEG / PNG)",
      "Legacy formats lack modern predictive compression and transparency handling, inflating file sizes by 30% to 70%.",
      "Convert content photography to WebP or AVIF. Use <picture> tags with fallback sources for backwards browser compatibility.",
      "Next-Gen Formats / Medium Priority",
    ],
    [
      "Missing HTML Width and Height",
      "Browsers cannot allocate layout space before images download, causing content to jump and degrading Cumulative Layout Shift (CLS).",
      "Specify intrinsic width=\"\" and height=\"\" or CSS aspect-ratio on all <img> elements to reserve display space upfront.",
      "Core Web Vitals (CLS) / Medium Priority",
    ],
    [
      "Lazy-Loading on Above-The-Fold / Hero Assets",
      "Applying loading=\"lazy\" to the main hero banner delays image discovery and rendering, severely hurting Largest Contentful Paint (LCP).",
      "Remove loading=\"lazy\" from the top 1-2 images in the initial viewport. Add fetchpriority=\"high\" to the primary hero image.",
      "LCP Optimization / High Priority",
    ],
    [
      "Broken Image Links (404 / 5xx)",
      "Broken images present an unprofessional user experience and waste browser connection threads.",
      "Update image URLs to active assets or remove orphaned <img> tags.",
      "Technical SEO / High Priority",
    ],
  ];

  // 7. Populate Crawl Log tab
  const logValues = [
    ["Page URL", "Status Code", "Page Title", "Response Time (ms)", "Images Discovered", "Result", "Notes"],
    ...crawlLog.map((log) => [
      log.url,
      log.statusCode,
      log.title || "-",
      log.responseTimeMs,
      log.imagesFound,
      log.status.toUpperCase(),
      log.notes || "OK",
    ]),
  ];

  // Write cell values
  await sheets.spreadsheets.values.batchUpdate({
    spreadsheetId,
    requestBody: {
      valueInputOption: "USER_ENTERED",
      data: [
        { range: "'Image Optimization'!A1", values: optValues },
        { range: "'Overview'!A1", values: summaryValues },
        { range: "'Image Inventory'!A1", values: invValues },
        { range: "'Recommendations'!A1", values: recValues },
        { range: "'Crawl Log'!A1", values: logValues },
      ],
    },
  });

  // 8. Style Image Optimization tab: Yellow header row, bold centered text, column widths & row heights
  const formattingRequests: any[] = [
    // Header row styling on Image Optimization (Sheet 0): Yellow fill (#FFE599), bold, centered
    {
      repeatCell: {
        range: {
          sheetId: 0,
          startRowIndex: 0,
          endRowIndex: 1,
          startColumnIndex: 0,
          endColumnIndex: 6,
        },
        cell: {
          userEnteredFormat: {
            backgroundColor: { red: 1.0, green: 0.95, blue: 0.6 }, // Reference Yellow
            textFormat: { bold: true, fontSize: 10 },
            horizontalAlignment: "CENTER",
            verticalAlignment: "MIDDLE",
          },
        },
        fields: "userEnteredFormat(backgroundColor,textFormat,horizontalAlignment,verticalAlignment)",
      },
    },
    // Set Header row height (32px)
    {
      updateDimensionProperties: {
        range: {
          sheetId: 0,
          dimension: "ROWS",
          startIndex: 0,
          endIndex: 1,
        },
        properties: { pixelSize: 32 },
        fields: "pixelSize",
      },
    },
    // Set Data rows height (130px for clear image preview)
    {
      updateDimensionProperties: {
        range: {
          sheetId: 0,
          dimension: "ROWS",
          startIndex: 1,
          endIndex: Math.max(2, items.length + 1),
        },
        properties: { pixelSize: 130 },
        fields: "pixelSize",
      },
    },
    // Set Column Widths on Image Optimization
    {
      updateDimensionProperties: {
        range: { sheetId: 0, dimension: "COLUMNS", startIndex: 0, endIndex: 1 },
        properties: { pixelSize: 300 }, // Col A: Image
        fields: "pixelSize",
      },
    },
    {
      updateDimensionProperties: {
        range: { sheetId: 0, dimension: "COLUMNS", startIndex: 1, endIndex: 2 },
        properties: { pixelSize: 380 }, // Col B: URL
        fields: "pixelSize",
      },
    },
    {
      updateDimensionProperties: {
        range: { sheetId: 0, dimension: "COLUMNS", startIndex: 2, endIndex: 3 },
        properties: { pixelSize: 300 }, // Col C: Title
        fields: "pixelSize",
      },
    },
    {
      updateDimensionProperties: {
        range: { sheetId: 0, dimension: "COLUMNS", startIndex: 3, endIndex: 4 },
        properties: { pixelSize: 65 },  // Col D: Length
        fields: "pixelSize",
      },
    },
    {
      updateDimensionProperties: {
        range: { sheetId: 0, dimension: "COLUMNS", startIndex: 4, endIndex: 5 },
        properties: { pixelSize: 350 }, // Col E: Optimized ALT Text
        fields: "pixelSize",
      },
    },
    {
      updateDimensionProperties: {
        range: { sheetId: 0, dimension: "COLUMNS", startIndex: 5, endIndex: 6 },
        properties: { pixelSize: 65 },  // Col F: Length
        fields: "pixelSize",
      },
    },
  ];

  try {
    await sheets.spreadsheets.batchUpdate({
      spreadsheetId,
      requestBody: { requests: formattingRequests },
    });
  } catch {
    // Styling failed non-fatally; sheet data remains intact
  }

  return { spreadsheetId, spreadsheetUrl };
}
