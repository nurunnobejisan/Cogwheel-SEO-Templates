import * as XLSX from "xlsx";
import type { CrawlLogEntry, ImageAuditItem, ImageAuditSummary } from "./types.ts";

export function generateImageAuditWorkbook(
  summary: ImageAuditSummary,
  items: ImageAuditItem[],
  crawlLog: CrawlLogEntry[]
): {
  workbook: XLSX.WorkBook;
  buffer: Buffer;
  base64: string;
} {
  const wb = XLSX.utils.book_new();

  // -------------------------------------------------------------------------
  // TAB 1: Image Optimization (STRICT 6-COLUMN LAYOUT MATCHING REFERENCE SHEET)
  // Headers: Image | URL  | Title  | Length | Optimized ALT Text | Length
  // Reference: https://docs.google.com/spreadsheets/d/1gdX3whxcXFlVNJDat2Avz_q3haNRfWz39TAMK0Q6QGc/
  // -------------------------------------------------------------------------
  const optHeaders = [
    "Image",
    "URL ",
    "Title ",
    "Length",
    "Optimized ALT Text",
    "Length",
  ];

  type CellValue = string | number | { f: string; v?: string | number; l?: { Target: string } };
  const optRows: CellValue[][] = [];

  items.forEach((item, idx) => {
    const rowNum = idx + 2; // Row 1 is header
    // Decoded filename including extension (or fallback)
    const titleVal = item.filename || item.imageUrl.split("/").pop()?.split("?")[0] || `Image on ${item.pageUrl}`;
    const altVal = item.proposedAlt || "";

    optRows.push([
      { f: `IMAGE(B${rowNum})` },
      { f: `HYPERLINK("${item.imageUrl}", "${item.imageUrl}")`, v: item.imageUrl, l: { Target: item.imageUrl } },
      titleVal,
      { f: `LEN(C${rowNum})`, v: titleVal.length },
      altVal,
      { f: `LEN(E${rowNum})`, v: altVal.length },
    ]);
  });

  const wsOpt = XLSX.utils.aoa_to_sheet([optHeaders, ...optRows]);

  // Exact column sizing matching the reference Google Sheet
  wsOpt["!cols"] = [
    { wch: 44.5 },  // Col A: Image preview
    { wch: 57.5 },  // Col B: URL
    { wch: 46.75 }, // Col C: Title
    { wch: 7.13 },  // Col D: Length
    { wch: 47.75 }, // Col E: Optimized ALT Text
    { wch: 7.13 },  // Col F: Length
  ];

  // Configure row heights: Header 28.5pt, data rows 190.5pt (matching reference sheet exactly)
  const optRowProps: { hpt?: number; customHeight?: boolean }[] = [
    { hpt: 28.5, customHeight: true }, // Row 1 header
  ];
  for (let i = 0; i < items.length; i++) {
    optRowProps.push({ hpt: 190.5, customHeight: true });
  }
  wsOpt["!rows"] = optRowProps;

  // Autofilter and frozen header row for row 1
  wsOpt["!autofilter"] = { ref: `A1:F${Math.max(1, items.length + 1)}` };
  (wsOpt as Record<string, unknown>)["!views"] = [{ state: "frozen", ySplit: 1 }];

  XLSX.utils.book_append_sheet(wb, wsOpt, "Image Optimization");

  // -------------------------------------------------------------------------
  // TAB 2: Overview (Exhaustive Coverage & Diagnostic Report)
  // -------------------------------------------------------------------------
  const summaryRows: (string | number)[][] = [
    ["WEBSITE IMAGE OPTIMIZATION AUDIT SUMMARY", ""],
    ["Generated By:", "Razib Marketing — SEO Studio"],
    ["Audited Website URL:", summary.websiteUrl],
    ["Origin Domain:", summary.origin],
    ["Audit Timestamp (UTC):", summary.crawledAt],
    ["Total Duration:", `${Math.round(summary.durationMs / 1000)} seconds`],
    ["Crawl Limit:", `${summary.maxPagesLimit} pages`],
    ["Crawl Status:", summary.crawlCompleted ? "Complete within crawl limits" : `Stopped: ${summary.stoppedReason}`],
    ["", ""],
    ["DISCOVERY & COVERAGE METHODS", "STATUS / METRIC"],
    ["Discovery Methods Deployed:", (summary.discoveryMethods || []).join(", ") || "Internal Crawl, Sitemaps, Lazy-Load"],
    ["XML Sitemap Discovery:", summary.sitemapDiscoverySucceeded ? `Succeeded (${summary.sitemapUrlsFound} URLs found)` : "None detected / Inaccessible"],
    ["WordPress REST Media API:", summary.wpMediaApiFound ? `Discovered (${summary.wpMediaCount} media items)` : "Not applicable / Inaccessible"],
    ["JavaScript Client-Rendering:", summary.jsRenderingInspected ? "Inspected" : "Static HTML & SSR DOM only"],
    ["Coverage Statement:", summary.coverageStatement || "Complete within crawlable public HTML pages and declared sitemaps."],
    ["", ""],
    ["KEY AUDIT TOTALS", "COUNT"],
    ["Pages Discovered:", summary.pagesDiscovered || summary.pagesScanned],
    ["Pages Successfully Scanned:", summary.pagesScanned],
    ["Pages Failed / Timed Out:", summary.pagesFailed],
    ["Total Image Placements (Occurrences):", summary.totalPlacementsCount || summary.totalImagesFound],
    ["Unique Image URLs (Distinct Assets):", summary.uniqueImagesCount],
    ["Images Successfully Reachable (HTTP 200):", summary.imagesPreviewedSuccessfully || (summary.totalImagesFound - summary.brokenImagesCount)],
    ["Broken Image Links (HTTP 4xx / 5xx):", summary.brokenImagesCount],
    ["Images Missing ALT Text:", summary.missingAltCount],
    ["Decorative Empty Alt Placements (alt=\"\"):", summary.decorativeEmptyAltCount],
    ["Oversized Assets (>100KB Threshold):", summary.oversizedImagesCount],
    ["Missing HTML Dimensions (CLS Risk):", summary.missingDimensionsCount],
    ["Legacy Formats (JPEG / PNG eligible for WebP/AVIF):", summary.legacyFormatCount],
    ["Lazy-Loaded Above-The-Fold / Hero Images:", summary.aboveFoldLazyCount],
    ["", ""],
    ["FORMAT BREAKDOWN", "ASSET COUNT"],
    ...Object.entries(summary.formatBreakdown || {}).map(([fmt, count]) => [fmt, count]),
    ...(summary.estimatedSavingsKb && summary.estimatedSavingsKb > 0
      ? [["Estimated Next-Gen Format Savings:", `~${summary.estimatedSavingsKb} KB (approx 35% reduction on legacy formats)`]]
      : []),
    ["", ""],
    ["IMPORTANT COVERAGE LIMITATIONS & NOTICE", ""],
    ["Completeness Boundary:", "This audit reflects images discovered on crawlable public HTML pages and referenced sitemaps. Pages gated by authentication, robots.txt exclusions, JavaScript-only SPAs, or firewall rate-limits could not be reached."],
    ["WCAG Decorative Images:", "Empty alt text (alt=\"\") is valid and recommended by WCAG 2.1 AA for purely decorative backgrounds, borders, and layout icons. Not all empty alt attributes represent defects."],
    ["Automated Alt Text:", "Proposed alt text strings are generated from contextual page titles, headings, and clean filename tokens. Review descriptions before deploying to production."],
    ["", ""],
    ["KEY FINDINGS & RECOMMENDATIONS", ""],
    ...(summary.topFindings || []).map((finding, idx) => [`${idx + 1}.`, finding]),
  ];

  if (summary.skippedAreas && summary.skippedAreas.length > 0) {
    summaryRows.push(["", ""]);
    summaryRows.push(["SKIPPED AREAS & ACCESS RESTRICTIONS", ""]);
    summary.skippedAreas.forEach((area) => summaryRows.push(["• Skipped Area:", area]));
  }

  if (summary.unresolvedErrors && summary.unresolvedErrors.length > 0) {
    summaryRows.push(["", ""]);
    summaryRows.push(["UNRESOLVED CRAWL ERRORS", ""]);
    summary.unresolvedErrors.forEach((err) => summaryRows.push(["• Error:", err]));
  }

  const wsSummary = XLSX.utils.aoa_to_sheet(summaryRows);
  wsSummary["!cols"] = [{ wch: 48 }, { wch: 65 }];
  (wsSummary as Record<string, unknown>)["!views"] = [{ state: "frozen", ySplit: 1 }];
  XLSX.utils.book_append_sheet(wb, wsSummary, "Overview");

  // -------------------------------------------------------------------------
  // TAB 3: Image Inventory (Comprehensive Technical Field-by-Field Audit)
  // -------------------------------------------------------------------------
  const invHeaders = [
    "Image URL",
    "Page URL",
    "Page Title",
    "Page Status",
    "Original Filename",
    "Target Filename (WebP)",
    "Current ALT",
    "Proposed ALT",
    "Is Decorative",
    "Format",
    "MIME Type",
    "File Size (KB)",
    "HTML Width",
    "HTML Height",
    "Natural Width",
    "Natural Height",
    "Loading Attribute",
    "Element Type",
    "Occurrences",
    "HTTP Status",
    "Flagged Issues",
    "Recommendation",
    "Priority",
  ];

  const invRows = items.map((item) => {
    const issueLabels = item.issues.map((i) => i.label).join("; ");
    return [
      item.imageUrl,
      item.pageUrl,
      item.pageTitle || "-",
      item.pageStatus,
      item.filename || "-",
      item.targetFilename || "-",
      item.currentAlt === null ? "[MISSING]" : item.currentAlt === "" ? '"" (Empty)' : item.currentAlt,
      item.proposedAlt,
      item.isDecorative ? "Yes (Decorative)" : "No",
      item.format,
      item.mimeType,
      item.fileSizeKb ? `${item.fileSizeKb} KB` : "-",
      item.htmlWidth ?? "-",
      item.htmlHeight ?? "-",
      item.naturalWidth ?? "-",
      item.naturalHeight ?? "-",
      item.loadingAttribute,
      item.elementType,
      item.occurrenceCount,
      item.httpStatus,
      issueLabels || "None (Optimal)",
      item.recommendation,
      item.priority,
    ];
  });

  const wsInv = XLSX.utils.aoa_to_sheet([invHeaders, ...invRows]);
  wsInv["!cols"] = [
    { wch: 45 }, // Image URL
    { wch: 35 }, // Page URL
    { wch: 28 }, // Page Title
    { wch: 10 }, // Page Status
    { wch: 28 }, // Original Filename
    { wch: 30 }, // Target Filename (WebP)
    { wch: 30 }, // Current ALT
    { wch: 35 }, // Proposed ALT
    { wch: 15 }, // Is Decorative
    { wch: 10 }, // Format
    { wch: 12 }, // MIME
    { wch: 12 }, // Size KB
    { wch: 10 }, // HTML W
    { wch: 10 }, // HTML H
    { wch: 10 }, // Nat W
    { wch: 10 }, // Nat H
    { wch: 14 }, // Loading
    { wch: 14 }, // Element
    { wch: 12 }, // Occurrences
    { wch: 10 }, // HTTP
    { wch: 35 }, // Issues
    { wch: 45 }, // Rec
    { wch: 10 }, // Priority
  ];
  wsInv["!autofilter"] = { ref: `A1:W${Math.max(1, items.length + 1)}` };
  (wsInv as Record<string, unknown>)["!views"] = [{ state: "frozen", ySplit: 1 }];
  XLSX.utils.book_append_sheet(wb, wsInv, "Image Inventory");

  // -------------------------------------------------------------------------
  // TAB 4: Recommendations (Actionable Performance & SEO Guide)
  // -------------------------------------------------------------------------
  const recHeaders = ["Issue Category", "Why It Matters", "Recommended Fix", "Industry Standard / Priority"];
  const recRows = [
    [
      "Missing Alt Attributes",
      "Screen readers cannot announce image content, and search engines cannot index image context for Google Images and web search.",
      "Add concise, descriptive alt text to all informational images. Purely decorative elements (dividers, borders, shadows) should use alt=\"\" or CSS background.",
      "WCAG 2.1 AA / High Priority",
    ],
    [
      "Oversized File Sizes (>100KB)",
      "Heavy assets consume cellular bandwidth, stall page rendering, and increase bounce rates, especially on mobile devices.",
      "Compress images using modern tools (Squoosh, Sharp, TinyPNG) and target under 100KB for standard content images (under 200KB for full-width hero banners).",
      "Core Web Vitals (LCP) / High Priority",
    ],
    [
      "Legacy Image Formats (JPEG / PNG)",
      "Legacy formats lack modern predictive compression and transparency handling, inflating file sizes by 30% to 70%.",
      "Convert content photography to WebP or AVIF. Use <picture> tags with fallback sources for backwards browser compatibility.",
      "Next-Gen Formats / Medium Priority",
    ],
    [
      "Missing HTML Width and Height",
      "Browsers cannot allocate layout space before images download, causing content to jump and degrading Cumulative Layout Shift (CLS).",
      "Specify intrinsic width=\"\" and height=\"\" or CSS aspect-ratio on all <img> elements to reserve display space upfront.",
      "Core Web Vitals (CLS) / Medium Priority",
    ],
    [
      "Lazy-Loading on Above-The-Fold / Hero Assets",
      "Applying loading=\"lazy\" to the main hero banner delays image discovery and rendering, severely hurting Largest Contentful Paint (LCP).",
      "Remove loading=\"lazy\" from the top 1-2 images in the initial viewport. Add fetchpriority=\"high\" to the primary hero image.",
      "LCP Optimization / High Priority",
    ],
    [
      "Broken Image Links (404 / 5xx)",
      "Broken images present an unprofessional user experience and waste browser connection threads.",
      "Update image URLs to active assets or remove orphaned <img> tags.",
      "Technical SEO / High Priority",
    ],
    [
      "Duplicate Image Asset Requests",
      "Re-requesting identical images across different pages without caching increases server load.",
      "Ensure consistent canonical image URLs and configure long-lived HTTP Cache-Control headers (e.g. max-age=31536000, immutable).",
      "Browser Caching / Low Priority",
    ],
  ];

  const wsRec = XLSX.utils.aoa_to_sheet([recHeaders, ...recRows]);
  wsRec["!cols"] = [{ wch: 25 }, { wch: 45 }, { wch: 55 }, { wch: 28 }];
  (wsRec as Record<string, unknown>)["!views"] = [{ state: "frozen", ySplit: 1 }];
  XLSX.utils.book_append_sheet(wb, wsRec, "Recommendations");

  // -------------------------------------------------------------------------
  // TAB 5: Crawl Log (Page-by-Page Diagnostic Log)
  // -------------------------------------------------------------------------
  const logHeaders = ["Page URL", "Status Code", "Page Title", "Response Time (ms)", "Images Discovered", "Result", "Notes"];
  const logRows = crawlLog.map((log) => [
    log.url,
    log.statusCode,
    log.title || "-",
    log.responseTimeMs,
    log.imagesFound,
    log.status.toUpperCase(),
    log.notes || "OK",
  ]);

  const wsLog = XLSX.utils.aoa_to_sheet([logHeaders, ...logRows]);
  wsLog["!cols"] = [
    { wch: 45 },
    { wch: 12 },
    { wch: 35 },
    { wch: 18 },
    { wch: 18 },
    { wch: 12 },
    { wch: 35 },
  ];
  wsLog["!autofilter"] = { ref: `A1:G${Math.max(1, crawlLog.length + 1)}` };
  (wsLog as Record<string, unknown>)["!views"] = [{ state: "frozen", ySplit: 1 }];
  XLSX.utils.book_append_sheet(wb, wsLog, "Crawl Log");

  const buffer = XLSX.write(wb, { type: "buffer", bookType: "xlsx" });
  const base64 = buffer.toString("base64");

  return {
    workbook: wb,
    buffer,
    base64,
  };
}
