import * as XLSX from "xlsx";
import type { CrawlLogEntry, ImageAuditItem, ImageAuditSummary } from "./types.ts";

export function generateImageAuditWorkbook(
  summary: ImageAuditSummary,
  items: ImageAuditItem[],
  crawlLog: CrawlLogEntry[]
): {
  workbook: XLSX.WorkBook;
  buffer: Buffer;
  base64: string;
} {
  const wb = XLSX.utils.book_new();

  // -------------------------------------------------------------------------
  // TAB 1: Image Optimization (Matches Reference Google Sheet Layout)
  // Headers: Image | URL | Title | Length | Optimized ALT Text | Length | Format | Size (KB) | Dimensions | Status | Recommendation | Priority
  // -------------------------------------------------------------------------
  const optHeaders = [
    "Image",
    "URL ",
    "Title ",
    "Length",
    "Optimized ALT Text",
    "Length",
    "Format",
    "Size (KB)",
    "Dimensions",
    "Status / Issue",
    "Recommendation",
    "Priority",
  ];

  const optRows: (string | number | { f: string })[][] = [];
  items.forEach((item, idx) => {
    const rowNum = idx + 2; // Row 1 is header
    const cleanTitle = item.imageUrl.split("/").pop()?.split("?")[0] || "Image";
    const dimText = item.htmlWidth && item.htmlHeight ? `${item.htmlWidth}x${item.htmlHeight}` : "-";
    const issueText = item.issues.length > 0 ? item.issues.map((i) => i.label).join("; ") : "Healthy";

    optRows.push([
      { f: `IMAGE(B${rowNum})` },
      item.imageUrl,
      cleanTitle,
      { f: `LEN(C${rowNum})` },
      item.proposedAlt,
      { f: `LEN(E${rowNum})` },
      item.format,
      item.fileSizeKb ?? "-",
      dimText,
      issueText,
      item.recommendation,
      item.priority,
    ]);
  });

  const wsOpt = XLSX.utils.aoa_to_sheet([optHeaders, ...optRows]);
  wsOpt["!cols"] = [
    { wch: 14 }, // Image formula
    { wch: 45 }, // URL
    { wch: 32 }, // Title
    { wch: 8 },  // Length
    { wch: 45 }, // Optimized ALT
    { wch: 8 },  // Length
    { wch: 10 }, // Format
    { wch: 10 }, // Size
    { wch: 14 }, // Dims
    { wch: 30 }, // Status/Issue
    { wch: 45 }, // Rec
    { wch: 10 }, // Priority
  ];
  wsOpt["!autofilter"] = { ref: `A1:L${Math.max(1, items.length + 1)}` };
  XLSX.utils.book_append_sheet(wb, wsOpt, "Image Optimization");

  // -------------------------------------------------------------------------
  // TAB 2: Overview (Executive KPI Cards & Findings)
  // -------------------------------------------------------------------------
  const overviewData = [
    ["WEBSITE IMAGE OPTIMIZATION AUDIT REPORT", ""],
    ["Generated By:", "Cogwheel SEO & Hospitality Templates Studio (Razib Marketing)"],
    ["Audited Website:", summary.websiteUrl],
    ["Origin Domain:", summary.origin],
    ["Audit Timestamp:", summary.crawledAt],
    ["Audit Duration:", `${Math.round(summary.durationMs / 1000)} seconds`],
    ["Crawl Limit:", `${summary.maxPagesLimit} pages`],
    ["", ""],
    ["EXECUTIVE AUDIT METRICS", "COUNT"],
    ["Total Public Pages Scanned", summary.pagesScanned],
    ["Pages with Crawl Errors", summary.pagesFailed],
    ["Total Image Assets Audited", summary.totalImagesFound],
    ["Broken Images (HTTP 4xx/5xx)", summary.brokenImagesCount],
    ["Missing Alt Text (<img alt missing>)", summary.missingAltCount],
    ["Suspicious/Empty Decorative Alt Text", summary.decorativeEmptyAltCount],
    ["Oversized Images (>100KB Threshold)", summary.oversizedImagesCount],
    ["Missing HTML Dimensions (CLS Risk)", summary.missingDimensionsCount],
    ["Legacy Formats (JPEG/PNG eligible for WebP/AVIF)", summary.legacyFormatCount],
    ["Lazy-Loaded Hero / Above-Fold Images", summary.aboveFoldLazyCount],
    ["", ""],
    ["FORMAT BREAKDOWN", "COUNT"],
    ...Object.entries(summary.formatBreakdown).map(([fmt, count]) => [fmt, count]),
    ["", ""],
    ["KEY AUDIT FINDINGS & RECOMMENDATIONS", ""],
    ...summary.topFindings.map((finding, i) => [`${i + 1}.`, finding]),
  ];

  const wsOverview = XLSX.utils.aoa_to_sheet(overviewData);
  wsOverview["!cols"] = [{ wch: 48 }, { wch: 35 }];
  XLSX.utils.book_append_sheet(wb, wsOverview, "Overview");

  // -------------------------------------------------------------------------
  // TAB 3: Image Inventory (Technical Field-by-Field Audit)
  // -------------------------------------------------------------------------
  const invHeaders = [
    "Image URL",
    "Page URL",
    "Page Title",
    "Page Status",
    "Current Alt Text",
    "Alt Status",
    "HTML Width",
    "HTML Height",
    "File Size (KB)",
    "Format",
    "MIME Type",
    "Element Type",
    "Loading Mode",
    "HTTP Status",
    "Occurrences",
    "Flagged Issues",
    "Actionable Recommendation",
    "Priority",
  ];

  const invRows = items.map((item) => {
    const altStatus = item.currentAlt === null ? "Missing" : item.isDecorative ? "Empty (Decorative)" : "Present";
    return [
      item.imageUrl,
      item.pageUrl,
      item.pageTitle,
      item.pageStatus,
      item.currentAlt || "-",
      altStatus,
      item.htmlWidth ?? "-",
      item.htmlHeight ?? "-",
      item.fileSizeKb ?? "-",
      item.format,
      item.mimeType,
      item.elementType,
      item.loadingAttribute,
      item.httpStatus || "ERR",
      item.occurrenceCount,
      item.issues.map((i) => i.label).join("; ") || "None",
      item.recommendation,
      item.priority,
    ];
  });

  const wsInv = XLSX.utils.aoa_to_sheet([invHeaders, ...invRows]);
  wsInv["!cols"] = [
    { wch: 45 }, // Image URL
    { wch: 40 }, // Page URL
    { wch: 30 }, // Page Title
    { wch: 11 }, // Page Status
    { wch: 30 }, // Current Alt
    { wch: 16 }, // Alt Status
    { wch: 11 }, // Width
    { wch: 11 }, // Height
    { wch: 13 }, // Size KB
    { wch: 10 }, // Format
    { wch: 14 }, // MIME
    { wch: 13 }, // Element Type
    { wch: 13 }, // Loading
    { wch: 12 }, // HTTP Status
    { wch: 12 }, // Occurrences
    { wch: 35 }, // Flagged Issues
    { wch: 45 }, // Recommendation
    { wch: 10 }, // Priority
  ];
  wsInv["!autofilter"] = { ref: `A1:R${Math.max(1, items.length + 1)}` };
  XLSX.utils.book_append_sheet(wb, wsInv, "Image Inventory");

  // -------------------------------------------------------------------------
  // TAB 4: Recommendations
  // -------------------------------------------------------------------------
  const recHeaders = ["Issue Category", "Why It Matters", "Recommended Fix", "Industry Standard / Priority"];
  const recRows = [
    [
      "Missing Alt Attributes",
      "Screen readers cannot announce image content, and search engines cannot index image context for Google Images and web search.",
      "Add concise, descriptive alt text to all informational images. Purely decorative elements (dividers, borders, shadows) should use alt=\"\" or CSS background.",
      "WCAG 2.1 AA / High Priority",
    ],
    [
      "Oversized File Sizes (>100KB)",
      "Heavy assets consume cellular bandwidth, stall page rendering, and increase bounce rates, especially on mobile devices.",
      "Compress images using modern tools (Squoosh, Sharp, TinyPNG) and target under 100KB for standard content images (under 200KB for full-width hero banners).",
      "Core Web Vitals (LCP) / High Priority",
    ],
    [
      "Legacy Image Formats (JPEG / PNG)",
      "Legacy formats lack modern predictive compression and transparency handling, inflating file sizes by 30% to 70%.",
      "Convert content photography to WebP or AVIF. Use <picture> tags with fallback sources for backwards browser compatibility.",
      "Next-Gen Formats / Medium Priority",
    ],
    [
      "Missing HTML Width and Height",
      "Browsers cannot allocate layout space before images download, causing content to jump and degrading Cumulative Layout Shift (CLS).",
      "Specify intrinsic width=\"\" and height=\"\" or CSS aspect-ratio on all <img> elements to reserve display space upfront.",
      "Core Web Vitals (CLS) / Medium Priority",
    ],
    [
      "Lazy-Loading on Above-The-Fold / Hero Assets",
      "Applying loading=\"lazy\" to the main hero banner delays image discovery and rendering, severely hurting Largest Contentful Paint (LCP).",
      "Remove loading=\"lazy\" from the top 1-2 images in the initial viewport. Add fetchpriority=\"high\" to the primary hero image.",
      "LCP Optimization / High Priority",
    ],
    [
      "Broken Image Links (404 / 5xx)",
      "Broken images present an unprofessional user experience and waste browser connection threads.",
      "Update image URLs to active assets or remove orphaned <img> tags.",
      "Technical SEO / High Priority",
    ],
    [
      "Duplicate Image Asset Requests",
      "Re-requesting identical images across different pages without caching increases server load.",
      "Ensure consistent canonical image URLs and configure long-lived HTTP Cache-Control headers (e.g. max-age=31536000, immutable).",
      "Browser Caching / Low Priority",
    ],
  ];

  const wsRec = XLSX.utils.aoa_to_sheet([recHeaders, ...recRows]);
  wsRec["!cols"] = [{ wch: 25 }, { wch: 45 }, { wch: 55 }, { wch: 28 }];
  XLSX.utils.book_append_sheet(wb, wsRec, "Recommendations");

  // -------------------------------------------------------------------------
  // TAB 5: Crawl Log
  // -------------------------------------------------------------------------
  const logHeaders = ["Page URL", "Status Code", "Page Title", "Response Time (ms)", "Images Discovered", "Crawl Status", "Notes"];
  const logRows = crawlLog.map((c) => [
    c.url,
    c.statusCode || "ERR",
    c.title || "-",
    c.responseTimeMs,
    c.imagesFound,
    c.status.toUpperCase(),
    c.notes || "-",
  ]);

  const wsLog = XLSX.utils.aoa_to_sheet([logHeaders, ...logRows]);
  wsLog["!cols"] = [
    { wch: 45 },
    { wch: 12 },
    { wch: 32 },
    { wch: 18 },
    { wch: 18 },
    { wch: 14 },
    { wch: 35 },
  ];
  wsLog["!autofilter"] = { ref: `A1:G${Math.max(1, crawlLog.length + 1)}` };
  XLSX.utils.book_append_sheet(wb, wsLog, "Crawl Log");

  const buffer = XLSX.write(wb, { type: "buffer", bookType: "xlsx" }) as Buffer;
  const base64 = buffer.toString("base64");

  return { workbook: wb, buffer, base64 };
}
