import { getDriveClient, getSheetsClient, isGoogleConfigured } from "../google.ts";
import type { HeadingAuditSummary, PageHeadingAudit } from "./types.ts";

export async function exportHeadingAuditToGoogleSheets(
  summary: HeadingAuditSummary,
  pages: PageHeadingAudit[]
): Promise<{ spreadsheetId: string; spreadsheetUrl: string }> {
  if (!isGoogleConfigured()) {
    throw new Error(
      "Google Workspace service account is not configured. Set GOOGLE_SERVICE_ACCOUNT_B64 or GOOGLE_SERVICE_ACCOUNT_JSON in environment variables."
    );
  }

  const drive = getDriveClient();
  const sheets = getSheetsClient();

  const title = `Heading Structure Optimization — ${new URL(summary.websiteUrl).hostname} (${new Date().toISOString().split("T")[0]})`;
  const folderId = process.env.GOOGLE_DRIVE_ROOT_FOLDER_ID || undefined;

  // 1. Create native Google Sheet
  const createRes = await drive.files.create({
    supportsAllDrives: true,
    requestBody: {
      name: title,
      mimeType: "application/vnd.google-apps.spreadsheet",
      ...(folderId ? { parents: [folderId] } : {}),
    },
    fields: "id, webViewLink",
  });

  const spreadsheetId = createRes.data.id!;
  const spreadsheetUrl =
    createRes.data.webViewLink || `https://docs.google.com/spreadsheets/d/${spreadsheetId}/edit`;

  // 2. Setup tabs: "Heading Optimization", "Audit Summary", "Hierarchy Analysis"
  const batchUpdateRequest = {
    requests: [
      {
        updateSheetProperties: {
          properties: {
            sheetId: 0,
            title: "Heading Optimization",
          },
          fields: "title",
        },
      },
      { addSheet: { properties: { sheetId: 1, title: "Audit Summary" } } },
      { addSheet: { properties: { sheetId: 2, title: "Hierarchy Analysis" } } },
    ],
  };

  await sheets.spreadsheets.batchUpdate({
    spreadsheetId,
    requestBody: batchUpdateRequest,
  });

  // 3. Build main rows
  const mainRows: string[][] = [];
  const headerRowIndices: number[] = [];
  const pageBannerRowIndices: number[] = [];

  let pageCounter = 1;

  pages.forEach((page) => {
    // Section Title
    pageBannerRowIndices.push(mainRows.length);
    mainRows.push([`${pageCounter}. ${page.subCategory.toUpperCase()} - `, "", "", "", "", ""]);

    // Table Header
    headerRowIndices.push(mainRows.length);
    mainRows.push([
      "Page URL",
      "Keyword ",
      "Old Headline",
      "Old Heading Level",
      "New Headline (optimized)",
      "New Heading Level",
    ]);

    // Headings
    if (page.headings.length === 0) {
      mainRows.push([
        page.pageUrl,
        page.targetKeyword,
        "[No Headings Found]",
        "NONE",
        `${page.targetKeyword} | Dressed To The Nines`,
        "H1",
      ]);
    } else {
      page.headings.forEach((h, hIdx) => {
        if (hIdx === 0) {
          mainRows.push([
            page.pageUrl,
            page.targetKeyword,
            h.originalText,
            h.tag,
            h.optimizedText,
            h.optimizedLevel,
          ]);
        } else {
          mainRows.push([
            "",
            "",
            h.originalText,
            h.tag,
            h.optimizedText,
            h.optimizedLevel,
          ]);
        }
      });
    }

    // Blank row
    mainRows.push(["", "", "", "", "", ""]);
    pageCounter++;
  });

  // 4. Populate Audit Summary tab
  const summaryRows: string[][] = [
    ["WEBSITE HEADING STRUCTURE OPTIMIZATION AUDIT SUMMARY", ""],
    ["Generated By:", "Cogwheel SEO & Hospitality Templates Studio"],
    ["Audited Website URL:", summary.websiteUrl],
    ["Origin Domain:", summary.origin],
    ["Audit Timestamp (UTC):", summary.auditedAt],
    ["Total Duration:", `${Math.round(summary.durationMs / 1000)} seconds`],
    ["Crawl Limit:", `${summary.maxPagesLimit} pages`],
    ["Crawl Status:", summary.crawlCompleted ? "Complete within crawl limits" : `Stopped: ${summary.stoppedReason}`],
    ["", ""],
    ["DISCOVERY & COVERAGE METHODS", "STATUS / METRIC"],
    ["Discovery Methods Deployed:", (summary.discoveryMethods || []).join(", ")],
    ["XML Sitemap Discovery:", summary.sitemapDiscoverySucceeded ? `Succeeded (${summary.sitemapUrlsFound} URLs discovered)` : "None detected / Inaccessible"],
    ["JavaScript Client-Rendering:", summary.jsRenderingInspected ? "Inspected" : "Static HTML & SSR DOM only"],
    ["Coverage Boundary Statement:", summary.coverageStatement],
    ["", ""],
    ["KEY AUDIT TOTALS", "COUNT"],
    ["Pages Discovered:", String(summary.pagesDiscovered)],
    ["Pages Successfully Scanned & Audited:", String(summary.pagesScanned)],
    ["Pages Failed / Timed Out:", String(summary.pagesFailed)],
    ["Total Heading Elements Inspected:", String(summary.totalHeadingsAudited)],
    ["Total <h1> Elements Found:", String(summary.h1TotalCount)],
    ["Total <h2> Elements Found:", String(summary.h2TotalCount)],
    ["Total <h3> Elements Found:", String(summary.h3TotalCount)],
    ["Total <h4>–<h6> Elements Found:", String(summary.h4H6TotalCount)],
    ["", ""],
    ["HIERARCHY ISSUES FLAGGED", "PAGE COUNT"],
    ["Pages Missing an <h1> Tag:", String(summary.pagesMissingH1Count)],
    ["Pages with Multiple <h1> Tags (Diluted Focus):", String(summary.pagesMultipleH1Count)],
    ["Pages with Skipped Heading Levels (e.g. H1 -> H3):", String(summary.pagesWithSkippedLevelsCount)],
    ["Empty Heading Elements Detected:", String(summary.emptyHeadingsCount)],
    ["", ""],
    ["KEY FINDINGS & STRATEGIC RECOMMENDATIONS", ""],
    ...(summary.topFindings || []).map((finding, idx) => [`${idx + 1}.`, finding]),
  ];

  // 5. Populate Hierarchy Analysis tab
  const invHeaders = [
    "Page URL",
    "Page Title",
    "Category",
    "Target Keyword",
    "Original Heading Text",
    "Current Level",
    "Optimized Heading Text",
    "Recommended Level",
    "Flagged Issues",
  ];
  const invRows: string[][] = [invHeaders];
  pages.forEach((page) => {
    page.headings.forEach((h) => {
      invRows.push([
        page.pageUrl,
        page.pageTitle,
        page.category,
        page.targetKeyword,
        h.originalText,
        h.tag,
        h.optimizedText,
        h.optimizedLevel,
        h.issues.map((i) => i.label).join("; ") || "Clean",
      ]);
    });
  });

  // Write values
  await sheets.spreadsheets.values.batchUpdate({
    spreadsheetId,
    requestBody: {
      valueInputOption: "USER_ENTERED",
      data: [
        { range: "'Heading Optimization'!A1", values: mainRows },
        { range: "'Audit Summary'!A1", values: summaryRows },
        { range: "'Hierarchy Analysis'!A1", values: invRows },
      ],
    },
  });

  // Formatting Requests: Yellow headers, green recommendations, column widths
  const formattingRequests: Record<string, unknown>[] = [
    // Column Widths on Sheet 0
    { updateDimensionProperties: { range: { sheetId: 0, dimension: "COLUMNS", startIndex: 0, endIndex: 1 }, properties: { pixelSize: 260 }, fields: "pixelSize" } },
    { updateDimensionProperties: { range: { sheetId: 0, dimension: "COLUMNS", startIndex: 1, endIndex: 2 }, properties: { pixelSize: 260 }, fields: "pixelSize" } },
    { updateDimensionProperties: { range: { sheetId: 0, dimension: "COLUMNS", startIndex: 2, endIndex: 3 }, properties: { pixelSize: 250 }, fields: "pixelSize" } },
    { updateDimensionProperties: { range: { sheetId: 0, dimension: "COLUMNS", startIndex: 3, endIndex: 4 }, properties: { pixelSize: 130 }, fields: "pixelSize" } },
    { updateDimensionProperties: { range: { sheetId: 0, dimension: "COLUMNS", startIndex: 4, endIndex: 5 }, properties: { pixelSize: 260 }, fields: "pixelSize" } },
    { updateDimensionProperties: { range: { sheetId: 0, dimension: "COLUMNS", startIndex: 5, endIndex: 6 }, properties: { pixelSize: 130 }, fields: "pixelSize" } },
  ];

  // Apply yellow header styling to all table header rows
  for (const r of headerRowIndices) {
    formattingRequests.push({
      repeatCell: {
        range: { sheetId: 0, startRowIndex: r, endRowIndex: r + 1, startColumnIndex: 0, endColumnIndex: 6 },
        cell: {
          userEnteredFormat: {
            backgroundColor: { red: 1.0, green: 0.9, blue: 0.6 }, // #FFE599
            textFormat: { bold: true, fontSize: 10 },
            horizontalAlignment: "CENTER",
            verticalAlignment: "MIDDLE",
          },
        },
        fields: "userEnteredFormat(backgroundColor,textFormat,horizontalAlignment,verticalAlignment)",
      },
    });
  }

  // Apply bold font to page banner rows
  for (const r of pageBannerRowIndices) {
    formattingRequests.push({
      repeatCell: {
        range: { sheetId: 0, startRowIndex: r, endRowIndex: r + 1, startColumnIndex: 0, endColumnIndex: 6 },
        cell: {
          userEnteredFormat: {
            textFormat: { bold: true, fontSize: 13 },
          },
        },
        fields: "userEnteredFormat(textFormat)",
      },
    });
  }

  try {
    await sheets.spreadsheets.batchUpdate({
      spreadsheetId,
      requestBody: { requests: formattingRequests },
    });
  } catch {
    // Non-fatal
  }

  return { spreadsheetId, spreadsheetUrl };
}
