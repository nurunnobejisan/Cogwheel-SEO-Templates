import * as XLSX from "xlsx";
import type { HeadingAuditSummary, PageHeadingAudit } from "./types.ts";

export function generateHeadingAuditWorkbook(
  summary: HeadingAuditSummary,
  pages: PageHeadingAudit[]
): {
  workbook: XLSX.WorkBook;
  buffer: Buffer;
  base64: string;
  filename: string;
} {
  const wb = XLSX.utils.book_new();

  // -------------------------------------------------------------------------
  // TAB 1: Heading Optimization (MATCHING REFERENCE SHEET LAYOUT EXACTLY)
  // Reference: https://docs.google.com/spreadsheets/d/1W_kydZFwQPl3qQ4Aybrh9JvQ1dXPG2-M/
  // Columns: Page URL | Keyword  | Old Headline | Old Heading Level | New Headline (optimized) | New Heading Level
  // -------------------------------------------------------------------------
  const mainRows: (string | number)[][] = [];

  // Group pages by category (Home, Accommodations, Dining, Experience, Meetings, Discover)
  let pageCounter = 1;

  pages.forEach((page) => {
    // 1. Page Title Header
    const sectionTitle = `${pageCounter}. ${page.subCategory.toUpperCase()} - `;
    mainRows.push([sectionTitle, "", "", "", "", ""]);

    // 2. Table Header Row (Yellow header in reference sheet)
    mainRows.push([
      "Page URL",
      "Keyword ",
      "Old Headline",
      "Old Heading Level",
      "New Headline (optimized)",
      "New Heading Level",
    ]);

    // 3. Headings for this page
    if (page.headings.length === 0) {
      mainRows.push([
        page.pageUrl,
        page.targetKeyword,
        "[No Headings Found]",
        "NONE",
        `${page.targetKeyword} | Dressed To The Nines`,
        "H1",
      ]);
    } else {
      page.headings.forEach((h, hIdx) => {
        if (hIdx === 0) {
          mainRows.push([
            page.pageUrl,
            page.targetKeyword,
            h.originalText,
            h.tag,
            h.optimizedText,
            h.optimizedLevel,
          ]);
        } else {
          mainRows.push([
            "", // Col A blank for subsequent rows matching reference
            "", // Col B blank for subsequent rows matching reference
            h.originalText,
            h.tag,
            h.optimizedText,
            h.optimizedLevel,
          ]);
        }
      });
    }

    // 4. Blank separation row
    mainRows.push(["", "", "", "", "", ""]);
    pageCounter++;
  });

  const wsMain = XLSX.utils.aoa_to_sheet(mainRows);

  // Exact column widths from the reference sheet
  wsMain["!cols"] = [
    { wch: 32.0 },  // Col A: Page URL
    { wch: 32.38 }, // Col B: Keyword
    { wch: 31.25 }, // Col C: Old Headline
    { wch: 16.0 },  // Col D: Old Heading Level
    { wch: 32.13 }, // Col E: New Headline (optimized)
    { wch: 16.25 }, // Col F: New Heading Level
  ];

  XLSX.utils.book_append_sheet(wb, wsMain, "Heading Optimization");

  // -------------------------------------------------------------------------
  // TAB 2: Audit Summary (Exhaustive Coverage & Diagnostics)
  // -------------------------------------------------------------------------
  const summaryRows: (string | number)[][] = [
    ["WEBSITE HEADING STRUCTURE OPTIMIZATION AUDIT SUMMARY", ""],
    ["Generated By:", "Cogwheel SEO & Hospitality Templates Studio (Razib Marketing)"],
    ["Audited Website URL:", summary.websiteUrl],
    ["Origin Domain:", summary.origin],
    ["Audit Timestamp (UTC):", summary.auditedAt],
    ["Total Duration:", `${Math.round(summary.durationMs / 1000)} seconds`],
    ["Crawl Limit:", `${summary.maxPagesLimit} pages`],
    ["Crawl Status:", summary.crawlCompleted ? "Complete within crawl limits" : `Stopped: ${summary.stoppedReason}`],
    ["", ""],
    ["DISCOVERY & COVERAGE METHODS", "STATUS / METRIC"],
    ["Discovery Methods Deployed:", (summary.discoveryMethods || []).join(", ")],
    ["XML Sitemap Discovery:", summary.sitemapDiscoverySucceeded ? `Succeeded (${summary.sitemapUrlsFound} URLs discovered)` : "None detected / Inaccessible"],
    ["JavaScript Client-Rendering:", summary.jsRenderingInspected ? "Inspected" : "Static HTML & SSR DOM only"],
    ["Coverage Boundary Statement:", summary.coverageStatement],
    ["", ""],
    ["KEY AUDIT TOTALS", "COUNT"],
    ["Pages Discovered:", summary.pagesDiscovered],
    ["Pages Successfully Scanned & Audited:", summary.pagesScanned],
    ["Pages Failed / Timed Out:", summary.pagesFailed],
    ["Total Heading Elements Inspected:", summary.totalHeadingsAudited],
    ["Total <h1> Elements Found:", summary.h1TotalCount],
    ["Total <h2> Elements Found:", summary.h2TotalCount],
    ["Total <h3> Elements Found:", summary.h3TotalCount],
    ["Total <h4>–<h6> Elements Found:", summary.h4H6TotalCount],
    ["", ""],
    ["HIERARCHY ISSUES FLAGGED", "PAGE COUNT"],
    ["Pages Missing an <h1> Tag:", summary.pagesMissingH1Count],
    ["Pages with Multiple <h1> Tags (Diluted Focus):", summary.pagesMultipleH1Count],
    ["Pages with Skipped Heading Levels (e.g. H1 -> H3):", summary.pagesWithSkippedLevelsCount],
    ["Empty Heading Elements Detected:", summary.emptyHeadingsCount],
    ["", ""],
    ["KEY FINDINGS & STRATEGIC RECOMMENDATIONS", ""],
    ...(summary.topFindings || []).map((finding, idx) => [`${idx + 1}.`, finding]),
  ];

  if (summary.unresolvedErrors && summary.unresolvedErrors.length > 0) {
    summaryRows.push(["", ""]);
    summaryRows.push(["UNRESOLVED CRAWL ERRORS & SKIPPED PAGES", ""]);
    summary.unresolvedErrors.forEach((err) => summaryRows.push(["• Error:", err]));
  }

  const wsSummary = XLSX.utils.aoa_to_sheet(summaryRows);
  wsSummary["!cols"] = [{ wch: 48 }, { wch: 65 }];
  XLSX.utils.book_append_sheet(wb, wsSummary, "Audit Summary");

  // -------------------------------------------------------------------------
  // TAB 3: Heading Hierarchy Analysis (Technical Inventory)
  // -------------------------------------------------------------------------
  const invHeaders = [
    "Page URL",
    "Page Title",
    "Category",
    "Target Keyword",
    "Original Heading Text",
    "Current Level",
    "Optimized Heading Text",
    "Recommended Level",
    "Flagged Issues",
  ];

  const invRows: (string | number)[][] = [];
  pages.forEach((page) => {
    page.headings.forEach((h) => {
      invRows.push([
        page.pageUrl,
        page.pageTitle,
        page.category,
        page.targetKeyword,
        h.originalText,
        h.tag,
        h.optimizedText,
        h.optimizedLevel,
        h.issues.map((i) => i.label).join("; ") || "Clean",
      ]);
    });
  });

  const wsInv = XLSX.utils.aoa_to_sheet([invHeaders, ...invRows]);
  wsInv["!cols"] = [
    { wch: 35 },
    { wch: 28 },
    { wch: 18 },
    { wch: 28 },
    { wch: 35 },
    { wch: 14 },
    { wch: 35 },
    { wch: 18 },
    { wch: 35 },
  ];
  wsInv["!autofilter"] = { ref: `A1:I${Math.max(1, invRows.length + 1)}` };
  XLSX.utils.book_append_sheet(wb, wsInv, "Hierarchy Analysis");

  const buffer = XLSX.write(wb, { type: "buffer", bookType: "xlsx" });
  const base64 = buffer.toString("base64");

  const hostname = new URL(summary.websiteUrl).hostname.replace(/[^a-z0-9]/gi, "_");
  const dateStr = new Date().toISOString().split("T")[0];
  const filename = `heading-structure-audit-${hostname}-${dateStr}.xlsx`;

  return {
    workbook: wb,
    buffer,
    base64,
    filename,
  };
}
